#!/usr/bin/env python3
"""Learn the LAB-local-line -> LE-input mux bits from routing fuzz designs
and emit them as Rust (tools/cram/src/le_mux_table.rs).

    python3 tools/explore/le_mux_table.py <design dir>... > tools/cram/src/le_mux_table.rs

For every LE input in the rcf fed from LOCAL_INTERCONNECT:X?Y?S0I<line>,
collect the residual (non-routing, non-LUT) bits in that LE's 4 CRAM rows,
as (frame - first LUT frame of the column, row within the LE, mirrored for
LEs 8-15). The mux bits for (line, port) are the bits present in every
sample; anything else in those rows belongs to other configuration.
"""
import collections, sys
sys.path.insert(0, 'tools/explore')
from residual import observed, flat_rowcol, placements, le_rows
import rcfpath as R

def lut_frame(x):
    width = lambda c: 166 if c in (13, 26, 52) else 27 if c == 39 else 35
    return 78 + sum(width(c) for c in range(1, x)) + 4 * sum(c <= x for c in (16, 50))

samples = collections.defaultdict(list)
for d in sys.argv[1:]:
    pos = collections.defaultdict(set)
    for (f, b), v in observed(d + '/diff.txt').items():
        if f >= 24:
            pos[flat_rowcol(f, b)[0]].add(f)
    pl = {name: (x, y, n) for x, y, n, name in placements(d)}
    rowuse = collections.Counter(tuple(le_rows(y, n)) for x, y, n in pl.values())
    for sig, items in R.parse_rcf(d + '/build/top.rcf'):
        last = None
        for k, v in items:
            if k == 'res':
                last = v
                continue
            if k != 'dest':
                continue
            cell, lport, rport = v
            if cell not in pl or last[0] != 'LOCAL_INTERCONNECT':
                continue
            x, y, n = pl[cell]
            rows = le_rows(y, n)
            if rowuse[tuple(rows)] > 1:
                continue
            bits = set()
            for i, r in enumerate(rows):
                ro = i if n // 2 < 8 else 3 - i
                for f in pos.get(r, ()):
                    bits.add((f - lut_frame(x), ro))
            samples[(last[4], rport or lport)].append(bits)

print('// @generated by tools/explore/le_mux_table.py from the routing fuzz')
print('// designs; do not edit by hand. (line, port) -> two mux bits as')
print('// (frame - lut_frame(x), row within LE; LEs 8-15 mirrored).')
print('pub const LE_INPUT_MUX: &[(u8, u8, [(i8, u8); 2])] = &[')
for (line, port), ss in sorted(samples.items()):
    core = set.intersection(*ss)
    # The input mux sits left of the LUT (frames -13..-2 in every sample
    # seen); this also drops unrelated bits a lone sample happens to share.
    core = sorted(b for b in core if -13 <= b[0] <= -2)
    if len(core) != 2:
        print(f'    // line {line} {port}: {len(ss)} samples, ambiguous {core}')
        continue
    p = 'ABCD'.index(port[-1])
    print(f'    ({line}, {p}, [({core[0][0]}, {core[0][1]}), ({core[1][0]}, {core[1][1]})]), // {len(ss)} samples')
print('];')
