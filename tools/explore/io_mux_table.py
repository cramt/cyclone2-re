#!/usr/bin/env python3
"""Learn the bottom-I/O-row local-line -> IO_DATAOUT mux bits from routing
fuzz designs and emit Rust (tools/cram/src/io_mux_table.rs).

    python3 tools/explore/io_mux_table.py <design dir>... > tools/cram/src/io_mux_table.rs

Each bottom I/O tile X has two output muxes. Even z sits right of the
tile's LUT-frame anchor, odd z is its mirror image (df -> -4 - df); both
use the same per-line pattern, so samples from either z teach one table:
(line) -> two bits (df from lut_frame(X) for even z, row - 2468).
"""
import collections, sys
sys.path.insert(0, 'tools/explore')
from residual import observed, flat_rowcol
import rcfpath as R

def lut_frame(x):
    width = lambda c: 166 if c in (13, 26, 52) else 27 if c == 39 else 35
    return 78 + sum(width(c) for c in range(1, x)) + 4 * sum(c <= x for c in (16, 50))

BOTTOM = 2468
per, common = {}, None
for d in sys.argv[1:]:
    s = {(f, flat_rowcol(f, b)[0]) for (f, b), v in observed(d + '/diff.txt').items()
         if f >= 24 and flat_rowcol(f, b)[0] >= BOTTOM}
    per[d] = s
    common = s if common is None else common & s

samples = collections.defaultdict(list)
for d in sys.argv[1:]:
    res = per[d] - common
    for sig, items in R.parse_rcf(d + '/build/top.rcf'):
        prev = None
        for k, v in items:
            if k == 'res' and v[0] == 'IO_DATAOUT' and v[2] == 0 and prev and prev[0] == 'LOCAL_INTERCONNECT':
                x, z, line = v[1], v[3], prev[4]
                L = lut_frame(x)
                side = range(L - 1, L + 4) if z % 2 == 0 else range(L - 7, L - 2)
                bits = {((f - L) if z % 2 == 0 else (-4 - (f - L)), r - BOTTOM) for f, r in res if f in side}
                samples[line].append(bits)
            if k == 'res':
                prev = v

print('// @generated by tools/explore/io_mux_table.py from the routing fuzz')
print('// designs; do not edit by hand. line -> two mux bits as (frame -')
print('// lut_frame(x) for even z, row - 2468); odd z mirrors df -> -4 - df.')
print('pub const IO_OUT_MUX: &[(u8, [(i8, u8); 2])] = &[')
for line, ss in sorted(samples.items()):
    core = sorted(set.intersection(*ss))
    if len(core) != 2:
        print(f'    // line {line}: {len(ss)} samples, ambiguous {core}')
        continue
    print(f'    ({line}, [({core[0][0]}, {core[0][1]}), ({core[1][0]}, {core[1][1]})]), // {len(ss)} samples')
print('];')
